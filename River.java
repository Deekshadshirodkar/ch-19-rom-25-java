class River {

    static String name = "Ganga";
    static int length = 2525;
    static boolean isClean = false;
    static float speed = 3.5f;
    static short depth = 30;
    static byte bridges = 18;
    static long code = 999999L;


    public static String getName() { 
		return name; 
		
	}
	
    public static int getLength() { 
		return length; 
		
	}
	
    public static boolean getIsClean() { 
		return isClean; 
		
	}
	
    public static float getSpeed() { 
		return speed; 
		
	}
	
    public static short getDepth() { 
		return depth; 
		
	}
	
    public static byte getBridges() { 
		return bridges; 
		
	}
	
    public static long getCode() { 
		return code; 
	
	}
}