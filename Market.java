class Market {

    static String name = "City Market";
    static int shops = 120;
    static boolean isOpen = true;
    static float area = 1500.5f;
    static short openingHour = 9;
    static byte rating = 5;
    static long license = 9988776655L;


    public static String getName() { 
		return name; 
		
	}
	
    public static int getShops() { 
		return shops; 
		
	}
	
    public static boolean getIsOpen() { 
		return isOpen; 
	
	}
	
    public static float getArea() { 
		return area; 
		
	}
	
    public static short getOpeningHour() { 
		return openingHour; 
		
	}
	
    public static byte getRating() { 
		return rating; 
		
	}
	
    public static long getLicense() { 
		return license; 
		
	}
}
