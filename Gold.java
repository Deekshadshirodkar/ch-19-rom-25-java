class Gold {

    static double weight = 24.5;
    static String purity = "22K";
    static boolean isHallmarked = true;
    static float price = 135000.0f;
    static short karat = 22;
    static byte count = 1;
    static long serial = 445566L;


    public static double getWeight() { 
		return weight; 
	
	}
	
    public static String getPurity() { 
		return purity; 
	
	}
	
    public static boolean getIsHallmarked() { 
		return isHallmarked; 
		
	}
	
    public static float getPrice() { 
		return price; 
	
	}
	
    public static short getKarat() { 
		return karat; 
	
	}
	
    public static byte getCount() { 
		return count; 
		
	}
	
    public static long getSerial() { 
		return serial; 
	
	}
	
}