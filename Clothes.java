class Clothes {

    static String type = "Shirt";
    static int size = 38;
    static char gender = 'M';
    static boolean isWashed = true;
    static float price = 799.99f;
    static short stock = 20;
    static byte rating = 4;

    public static String getType() { 
		return type; 
	
	}
	
    public static int getSize() { 
		return size; 
	
	}
	
    public static char getGender() { 
		return gender; 
		
	}
	
    public static boolean getIsWashed() { 
		return isWashed; 
		
	}
	
    public static float getPrice() { 
		return price; 
		
	}
	
    public static short getStock() { 
		return stock; 
		
	}
	
    public static byte getRating() { 
		return rating; 
		
	}
}